package com.ecoapi.techstore.user.domain.valueobjects;

/**
 * Enum representing the type of address in a user's address book.
 *
 * SHIPPING: Address used for shipping purposes
 * BILLING: Address used for billing purposes
 * BOTH: Address can be used for both shipping and billing
 */
public enum AddressType {
    SHIPPING,
    BILLING,
    BOTH
}
